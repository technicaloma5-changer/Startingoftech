#include <iostream>
using namespace std;

int main() {

    // Two numbers for arithmetic operations
    int a = 20;
    int b = 6;

    // Addition
    cout << "Addition: " << a + b << endl;

    // Subtraction
    cout << "Subtraction: " << a - b << endl;

    // Multiplication
    cout << "Multiplication: " << a * b << endl;

    // Division
    cout << "Division: " << a / b << endl;

    // Modulus gives the remainder
    cout << "Remainder: " << a % b << endl;

    return 0;
}