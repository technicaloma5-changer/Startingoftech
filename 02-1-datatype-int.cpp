#include <iostream>
using namespace std;

int main() {

    // int data type is used to store whole numbers.
    // It can store positive numbers, negative numbers, and zero.

    int age = 18;
    int marks = 85;
    int temperature = -5;

    // Displaying integer values
    cout << "Age: " << age << endl;
    cout << "Marks: " << marks << endl;
    cout << "Temperature: " << temperature << endl;

    return 0;
}