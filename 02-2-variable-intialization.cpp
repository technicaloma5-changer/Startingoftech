#include <iostream>
using namespace std;

int main() {

    // Variable initialization
    int age = 20;          //age variable stores 20
    float height = 5.8f;//height variable stores 5.8 as float
    double price = 99.99;//price variable stores 99.99 as double 
    char grade = 'A';//grade variable stores A as character 
    bool isStudent = true;//isStudent variable stores true as 1 

    // Display values
    cout << "Age: " << age << endl;
    cout << "Height: " << height << endl;
    cout << "Price: " << price << endl;
    cout << "Grade: " << grade << endl;
    cout << "Is Student: " << isStudent << endl;

    return 0;
}
